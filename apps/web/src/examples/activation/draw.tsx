import { act, type Act } from "./act.js";

/** The activation's shape as a button icon: the curve itself, so the choice
 *  is made by what the function looks like rather than by its name. */
export function Glyph({ kind, x, y }: { kind: Act; x?: number; y?: number }) {
  const pts: string[] = [];
  for (let i = 0; i <= 24; i++) {
    const z = -3 + (6 * i) / 24;
    let v: number;
    if (kind === "sigmoid") v = act("sigmoid", z * 1.6);
    else if (kind === "tanh") v = (act("tanh", z * 0.8) + 1) / 2;
    else if (kind === "relu") v = act("relu", z) / 3;
    else v = (z + 3) / 6;
    pts.push(`${(1 + i).toFixed(1)},${(13 - v * 12).toFixed(2)}`);
  }
  return (
    <svg className="af-glyph" x={x} y={y} width={26} height={14} viewBox="0 0 26 14" aria-hidden="true">
      <line x1={0} y1={13} x2={26} y2={13} />
      <path d={`M ${pts.join(" L ")}`} />
    </svg>
  );
}

export function ArrowDefs({ id }: { id: string }) {
  return (
    <defs>
      <marker id={id} viewBox="0 0 8 8" refX="7" refY="4" markerWidth="6" markerHeight="6" orient="auto">
        <path d="M0,0.5 L8,4 L0,7.5 Z" className="af-arrowhead" />
      </marker>
    </defs>
  );
}

/** A heavily rounded square: the digit recognizer's neuron. */
export function Neuron({
  cx,
  cy,
  size = 25,
  fill,
  className = "af-node",
}: {
  cx: number;
  cy: number;
  size?: number;
  fill: string;
  className?: string;
}) {
  const rx = size * 0.36;
  return (
    <rect
      className={className}
      x={cx - size / 2}
      y={cy - size / 2}
      width={size}
      height={size}
      rx={rx}
      ry={rx}
      style={{ fill }}
    />
  );
}

